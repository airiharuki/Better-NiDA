<#
.SYNOPSIS
    Builds self-contained installers for the release page.

.DESCRIPTION
    The repository install scripts expect the layout files to sit next to them,
    which forces an average user to clone the repo first. This generates
    single-file installers with the layout data embedded, so the release page
    offers "download one file, run one command".

        dist/install-nida.sh            Linux   - both XKB layouts embedded
        dist/install-nida-macos.command macOS   - both .keylayout files embedded,
                                                 double-clickable in Finder

    The payload is embedded as a quoted heredoc rather than base64, so the
    layout stays readable inside the installer. That matters for power users:
    the installed file (~/.xkb/symbols/nida, ~/Library/Keyboard Layouts/...)
    is plain text and remains editable after install.

    Both files are syntax-checked with bash -n, and the embedded payload is
    extracted and compared byte-for-byte against the source layout, so a
    corrupted or truncated embed fails here rather than on a user's machine.

.PARAMETER OutDir
    Where to write the installers. Defaults to ./dist.

.EXAMPLE
    .\scripts\build_installers.ps1
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)] [string]$OutDir = $null
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if (-not $OutDir) { $OutDir = Join-Path $root 'dist' }

function New-Utf8File([string]$Path, [string]$Content) {
    $dir = Split-Path -Parent $Path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    # Force LF: a CRLF-tainted shebang makes every shell reject the script.
    $Content = $Content.Replace("`r`n", "`n")
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding $false))
}

function Get-BashPath {
    foreach ($p in @('C:\Program Files\Git\bin\bash.exe', 'C:\Program Files\Git\usr\bin\bash.exe')) {
        if (Test-Path $p) { return $p }
    }
    $c = Get-Command bash -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    return $null
}

# ---------------------------------------------------------------------------
# payload guards: a heredoc terminator inside the payload would truncate it
# ---------------------------------------------------------------------------
$DELIM = 'NIDA_EMBEDDED_LAYOUT_EOF'

$payloads = @(
    @{ Name = 'nida';              Path = (Join-Path $root 'linux\nida');                        Delim = 'NIDA_XKB_NIDA_EOF' }
    @{ Name = 'nida_legacy';       Path = (Join-Path $root 'linux\nida_legacy');                 Delim = 'NIDA_XKB_LEGACY_EOF' }
    @{ Name = 'nida_midpoint';     Path = (Join-Path $root 'linux\nida_midpoint');               Delim = 'NIDA_XKB_MIDPOINT_EOF' }
    @{ Name = 'Khmer NiDA';        Path = (Join-Path $root 'macos\Khmer NiDA.keylayout');        Delim = 'NIDA_MAC_NIDA_EOF' }
    @{ Name = 'Khmer NiDA Legacy'; Path = (Join-Path $root 'macos\Khmer NiDA Legacy.keylayout'); Delim = 'NIDA_MAC_LEGACY_EOF' }
    @{ Name = 'Khmer Better-NiDA'; Path = (Join-Path $root 'macos\Khmer Better-NiDA.keylayout'); Delim = 'NIDA_MAC_MIDPOINT_EOF' }
)

foreach ($p in $payloads) {
    if (-not (Test-Path $p.Path)) { throw "missing payload: $($p.Path)" }
    $body = [System.IO.File]::ReadAllText($p.Path)
    if ($body -match [regex]::Escape($p.Delim)) {
        throw "payload $($p.Name) contains its own heredoc terminator $($p.Delim) - pick a different delimiter"
    }
    if ($body -match "`r`n") { throw "payload $($p.Name) has CRLF line endings; it must be LF" }
}

# ---------------------------------------------------------------------------
# Linux installer
# ---------------------------------------------------------------------------
$linux = New-Object System.Text.StringBuilder
[void]$linux.AppendLine('#!/usr/bin/env bash')
[void]$linux.AppendLine('#')
[void]$linux.AppendLine('#  Khmer NiDA Layout - for Linux')
[void]$linux.AppendLine('#')
[void]$linux.AppendLine('#  Self-contained installer. No clone needed, no root needed.')
[void]$linux.AppendLine('#  Generated by scripts/build_installers.ps1 - do not edit by hand.')
[void]$linux.AppendLine('#')
[void]$linux.AppendLine('#    ./install-nida.sh              install both, activate "nida"')
[void]$linux.AppendLine('#    ./install-nida.sh nida         activate Khmer NiDA')
[void]$linux.AppendLine('#    ./install-nida.sh nida_legacy  activate Khmer NiDA Legacy')
[void]$linux.AppendLine('#    ./install-nida.sh --test       check only, change nothing')
[void]$linux.AppendLine('#    ./install-nida.sh --remove     remove both')
[void]$linux.AppendLine('#')
[void]$linux.AppendLine('set -euo pipefail')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('XKB="$HOME/.xkb"')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('say()  { printf ''\033[32m==>\033[0m %s\n'' "$1"; }')
[void]$linux.AppendLine('die()  { printf ''\033[31merror:\033[0m %s\n'' "$1" >&2; exit 1; }')
[void]$linux.AppendLine('warn() { printf ''\033[33mwarn:\033[0m %s\n'' "$1" >&2; }')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('# ---------------------------------------------------------------- layout data')
[void]$linux.AppendLine('<<NIDA_XKB_NIDA_EOF')
[void]$linux.Append(([System.IO.File]::ReadAllText((Join-Path $root 'linux\nida'))).TrimEnd("`n"))
[void]$linux.AppendLine('')
[void]$linux.AppendLine('NIDA_XKB_NIDA_EOF')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('<<NIDA_XKB_LEGACY_EOF')
[void]$linux.Append(([System.IO.File]::ReadAllText((Join-Path $root 'linux\nida_legacy'))).TrimEnd("`n"))
[void]$linux.AppendLine('')
[void]$linux.AppendLine('NIDA_XKB_LEGACY_EOF')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('<<NIDA_XKB_MIDPOINT_EOF')
[void]$linux.Append(([System.IO.File]::ReadAllText((Join-Path $root 'linux\nida_midpoint'))).TrimEnd("`n"))
[void]$linux.AppendLine('')
[void]$linux.AppendLine('NIDA_XKB_MIDPOINT_EOF')
[void]$linux.AppendLine('')
[void]$linux.AppendLine('# ------------------------------------------------------------------- installer')
[void]$linux.AppendLine(@'
if [ "${1-}" = "--remove" ]; then
    rm -f "$XKB/symbols/nida" "$XKB/symbols/nida_legacy" "$XKB/symbols/nida_midpoint"
    if [ -f "$XKB/rules/evdev.lst" ]; then
        sed -i '/# >>> Better-NiDA/,/# <<< Better-NiDA/d' "$XKB/rules/evdev.lst" 2>/dev/null || true
    fi
    say "removed. pick another layout with: setxkbmap -layout us"
    exit 0
fi

command -v setxkbmap >/dev/null 2>&1 || die "setxkbmap not found. Install x11-xkb-utils (Debian/Ubuntu/Fedora/Arch)."

mkdir -p "$XKB/symbols" "$XKB/rules"
extract() {
    # $1 = heredoc delimiter, $2 = destination file
    # The opener is "<<DELIM"; the closer is "DELIM" alone. Match the opener by
    # suffix and strip both marker lines, or the payload comes out empty.
    sed -n "/^<<$1\$/,/^$1\$/ { /^<<$1\$/d; /^$1\$/d; p; }" "$0" > "$2"
}
extract NIDA_XKB_NIDA_EOF     "$XKB/symbols/nida"
extract NIDA_XKB_LEGACY_EOF   "$XKB/symbols/nida_legacy"
extract NIDA_XKB_MIDPOINT_EOF "$XKB/symbols/nida_midpoint"
say "installed ~/.xkb/symbols/nida, nida_legacy, and nida_midpoint"

# register in the rules file (classic format, still read by libxkbcomp, no root)
touch "$XKB/rules/evdev.lst"
if ! grep -q '# >>> Better-NiDA' "$XKB/rules/evdev.lst" 2>/dev/null; then
    cat >> "$XKB/rules/evdev.lst" <<'RULES'

# >>> Better-NiDA
! model          layout     variant
  *             nida
  *             nida_legacy
  *             nida_midpoint
# <<< Better-NiDA
RULES
    say "registered layouts in ~/.xkb/rules/evdev.lst"
fi

if command -v xkbcomp >/dev/null 2>&1; then
    xkbcomp -w0 -I"$XKB" -I/usr/share/X11/xkb symbols/nida >/dev/null 2>&1 \
        && say "xkbcomp: nida compiles" \
        || warn "xkbcomp could not compile nida - check ~/.xkb/symbols/nida"
fi

if [ "${1-}" = "--test" ]; then
    say "test mode: nothing activated"
    exit 0
fi

TARGET="${1:-nida}"
case "$TARGET" in
    nida|nida_legacy|nida_midpoint) ;;
    *) die "unknown layout '$TARGET' (use nida, nida_legacy, or nida_midpoint)" ;;
esac

setxkbmap -layout "$TARGET" || die "setxkbmap failed"
say "activated: $TARGET"

cat <<'NOTES'

Done. To keep this across logins:

  echo 'setxkbmap -layout nida' >> ~/.xprofile

Desktop menus: GNOME/KDE/Xfce -> Keyboard -> Layouts -> Add -> Others ->
look for "Khmer NiDA".

Change later:      setxkbmap -layout nida_legacy
Edit the layout:   nano ~/.xkb/symbols/nida   (plain text)
Re-apply:          setxkbmap -layout nida

LIGATURE NOTE
  XKB gives each key one character per level, so the Windows driver's
  multi-character ligatures (Shift+A, Shift+V, Shift+;, comma) emit only
  their first code point here. Those lines are marked "LIGATURE truncated".
  Everything else, including the coeng and the zero-width space, is faithful.

  Quick check:  J -> U+17D2, Space -> U+200B, Shift+Space -> U+0020
NOTES
'@)
$linuxPath = Join-Path $OutDir 'install-nida.sh'
New-Utf8File $linuxPath $linux.ToString()

# ---------------------------------------------------------------------------
# macOS installer (.command is double-clickable in Finder)
# ---------------------------------------------------------------------------
$mac = New-Object System.Text.StringBuilder
[void]$mac.AppendLine('#!/usr/bin/env bash')
[void]$mac.AppendLine('#')
[void]$mac.AppendLine('#  Khmer NiDA Layout - for macOS')
[void]$mac.AppendLine('#')
[void]$mac.AppendLine('#  Self-contained installer. Double-click this file in Finder, or run it')
[void]$mac.AppendLine('#  from Terminal:  bash install-nida-macos.command')
[void]$mac.AppendLine('#  Generated by scripts/build_installers.ps1 - do not edit by hand.')
[void]$mac.AppendLine('#')
[void]$mac.AppendLine('set -euo pipefail')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('DEST="$HOME/Library/Keyboard Layouts"')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('say() { printf ''\033[32m==>\033[0m %s\n'' "$1"; }')
[void]$mac.AppendLine('die() { printf ''\033[31merror:\033[0m %s\n'' "$1" >&2; exit 1; }')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('# ---------------------------------------------------------------- layout data')
[void]$mac.AppendLine('<<NIDA_MAC_NIDA_EOF')
[void]$mac.Append(([System.IO.File]::ReadAllText((Join-Path $root 'macos\Khmer NiDA.keylayout'))).TrimEnd("`n"))
[void]$mac.AppendLine('')
[void]$mac.AppendLine('NIDA_MAC_NIDA_EOF')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('<<NIDA_MAC_LEGACY_EOF')
[void]$mac.Append(([System.IO.File]::ReadAllText((Join-Path $root 'macos\Khmer NiDA Legacy.keylayout'))).TrimEnd("`n"))
[void]$mac.AppendLine('')
[void]$mac.AppendLine('NIDA_MAC_LEGACY_EOF')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('<<NIDA_MAC_MIDPOINT_EOF')
[void]$mac.Append(([System.IO.File]::ReadAllText((Join-Path $root 'macos\Khmer Better-NiDA.keylayout'))).TrimEnd("`n"))
[void]$mac.AppendLine('')
[void]$mac.AppendLine('NIDA_MAC_MIDPOINT_EOF')
[void]$mac.AppendLine('')
[void]$mac.AppendLine('# ------------------------------------------------------------------- installer')
[void]$mac.AppendLine(@'
[ "$(uname -s)" = "Darwin" ] || die "this installer is macOS only"

mkdir -p "$DEST"
extract() {
    # opener is "<<DELIM", closer is "DELIM" alone; strip both marker lines
    sed -n "/^<<$1\$/,/^$1\$/ { /^<<$1\$/d; /^$1\$/d; p; }" "$0" > "$2"
}
extract NIDA_MAC_NIDA_EOF     "$DEST/Khmer NiDA.keylayout"
extract NIDA_MAC_LEGACY_EOF   "$DEST/Khmer NiDA Legacy.keylayout"
extract NIDA_MAC_MIDPOINT_EOF "$DEST/Khmer Better-NiDA.keylayout"
say "copied layouts to ~/Library/Keyboard Layouts"

killall -HUP SystemUIServer 2>/dev/null || true

cat <<'NOTES'

NEXT STEP - one thing a script cannot reliably do for you:

  System Settings -> Keyboard -> Text Input -> Edit...
  then "+" -> Others... and pick "Khmer NiDA" or "Khmer NiDA Legacy".

If they do not appear straight away, log out and back in: macOS caches the
keyboard layout list and the installer only nudges it.

Enable from the shell instead:

  defaults write com.apple.HIToolbox AppleEnabledInputSources -array-add '<dict>
    <key>InputSourceKind</key><string>Keyboard Layout</string>
    <key>KeyboardLayout Name</key><string>Khmer NiDA</string>
  </dict>'
  killall SystemUIServer

CHECK (look for these):
  J            -> U+17D2  coeng
  Shift+J      -> U+1789  nyo
  Space        -> U+200B  zero-width space
  Shift+Space  -> U+0020  real space
  AltGr+Space  -> U+00A0  NBSP
  Shift+A      -> U+17B6 U+17C6  in one press

All five ligatures work on macOS, unlike Linux.

EDITING:
  open -e ~/Library/"Keyboard Layouts"/"Khmer NiDA.keylayout"
  (plain XML; copy back over, then log out and back in)

UNDO:
  rm ~/Library/Keyboard\ Layouts/Khmer*.keylayout
  killall SystemUIServer
  and remove them from System Settings -> Keyboard -> Text Input

Found a bug? https://github.com/airiharuki/Better-NiDA/issues
NOTES

echo ""
read -r -p "Press Enter to close this window..." _
'@)
$macPath = Join-Path $OutDir 'install-nida-macos.command'
New-Utf8File $macPath $mac.ToString()

# ---------------------------------------------------------------------------
# validate: bash syntax, and payload round-trip
# ---------------------------------------------------------------------------
$bash = Get-BashPath
$fail = 0
Write-Host ''
foreach ($f in @($linuxPath, $macPath)) {
    $bytes = [System.IO.File]::ReadAllBytes($f)
    $crlf = 0
    for ($i = 1; $i -lt $bytes.Length; $i++) { if ($bytes[$i] -eq 10 -and $bytes[$i-1] -eq 13) { $crlf++ } }
    $name = Split-Path -Leaf $f
    if ($crlf -gt 0) { Write-Host "   FAIL $name contains $crlf CRLF sequences (shebang would break)" -ForegroundColor Red; $fail++ }
    else { Write-Host "   ok   $name has LF endings" }

    if (-not $bash) {
        Write-Host "   skip $name syntax check (no bash available)" -ForegroundColor Yellow
    } else {
        $out = & $bash -n $f 2>&1
        if ($LASTEXITCODE -eq 0) { Write-Host "   ok   $name passes bash -n" }
        else { Write-Host "   FAIL $name syntax: $out" -ForegroundColor Red; $fail++ }
    }
}

# payload round-trip: extract with the same sed the installer uses
if ($bash) {
    $tmp = Join-Path $env:TEMP "nida_payload_check"
    if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
    New-Item -ItemType Directory -Path $tmp | Out-Null
    $extract = @'
set -e
src="$1"; dest="$2"; delim="$3"
sed -n "/^<<$delim\$/,/^$delim\$/ { /^<<$delim\$/d; /^$delim\$/d; p; }" "$src" > "$dest"
'@
    $extractScript = Join-Path $tmp 'extract.sh'
    New-Utf8File $extractScript $extract

    $checks = @(
        @{ File = $linuxPath; Delim = 'NIDA_XKB_NIDA_EOF';     Want = (Join-Path $root 'linux\nida') }
        @{ File = $linuxPath; Delim = 'NIDA_XKB_LEGACY_EOF';   Want = (Join-Path $root 'linux\nida_legacy') }
        @{ File = $linuxPath; Delim = 'NIDA_XKB_MIDPOINT_EOF'; Want = (Join-Path $root 'linux\nida_midpoint') }
        @{ File = $macPath;   Delim = 'NIDA_MAC_NIDA_EOF';     Want = (Join-Path $root 'macos\Khmer NiDA.keylayout') }
        @{ File = $macPath;   Delim = 'NIDA_MAC_LEGACY_EOF';   Want = (Join-Path $root 'macos\Khmer NiDA Legacy.keylayout') }
        @{ File = $macPath;   Delim = 'NIDA_MAC_MIDPOINT_EOF'; Want = (Join-Path $root 'macos\Khmer Better-NiDA.keylayout') }
    )
    foreach ($c in $checks) {
        $got = Join-Path $tmp (([System.IO.Path]::GetFileNameWithoutExtension($c.File)) + '-' + $c.Delim + '.out')
        & $bash $extractScript $c.File $got $c.Delim 2>&1 | Out-Null
        $a = [System.IO.File]::ReadAllText($c.Want).TrimEnd("`n")
        $b = [System.IO.File]::ReadAllText($got).TrimEnd("`n")
        $label = "$($c.Delim)"
        if ($a -eq $b) { Write-Host "   ok   payload $label round-trips identically" }
        else { Write-Host "   FAIL payload $label differs from source" -ForegroundColor Red; $fail++ }
    }
}

Write-Host ''
foreach ($f in @($linuxPath, $macPath)) {
    Write-Host ("   {0,-34} {1,7} bytes" -f (Split-Path -Leaf $f), (Get-Item $f).Length)
}

# Build Windows standalone runner and m17n copy in dist/
& (Join-Path $PSScriptRoot 'build_windows_runner.ps1') -OutExe (Join-Path $OutDir 'BetterNiDA-Midpoint-Windows.exe')
Copy-Item (Join-Path $root 'linux\m17n\nida-midpoint.mim') (Join-Path $OutDir 'nida-midpoint.mim') -Force

if ($fail -gt 0) { Write-Host "`n$fail installer problem(s)." -ForegroundColor Red; exit 1 }
Write-Host "`ninstallers built and validated -> $OutDir"